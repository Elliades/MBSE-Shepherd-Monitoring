/* The scenario library: checks every DSL file, compiles it to the plugin format and bundles the texts for the
   viewer (scenarios/index.html, which also works from the disk, without a server).

     scenarios/library/       public scenarios     -> scenarios/out/<id>.scenario.json, scenarios/library.js
     scenarios/private/       gitignored (answers) -> scenarios/private/out/,          scenarios/library-private.js

   Checks: each file parses; each scenario compiles (its given, sequence and from found, no loop); the text
   round trip (parse, print, parse gives the same document); the JSON round trip (the compiled file, read back
   as DSL and compiled again, says the same thing to the plugin).
   node scripts/scenarios-build.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DSL = require(path.join(ROOT, 'scenarios/scenario-dsl.js'));

function loadDir(dir, skip) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!skip || !skip.includes(e.name)) out.push(...loadDir(p, skip)); }
    else if (e.name.endsWith('.scn')) out.push({ path: path.relative(path.join(ROOT, 'scenarios'), p).replace(/\\/g, '/'), text: fs.readFileSync(p, 'utf8') });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path));
}
const pub = loadDir(path.join(ROOT, 'scenarios/library'));
const priv = loadDir(path.join(ROOT, 'scenarios/private'), ['out']);
/* the private scenarios may refer to the public ones, not the other way round */
const all = DSL.load(pub.concat(priv));
const pubIds = new Set(DSL.load(pub).files.map((f) => f.id));

let errors = 0;
let warnings = 0;
const outDirs = { pub: path.join(ROOT, 'scenarios/out'), priv: path.join(ROOT, 'scenarios/private/out') };
for (const d of Object.values(outDirs)) { fs.rmSync(d, { recursive: true, force: true }); fs.mkdirSync(d, { recursive: true }); }

for (const f of all.files) {
  const where = `scenarios/${f.path}`;
  f.errors.forEach((e) => { console.error(`✗ ${where}:${e.line} ${e.message}`); errors += 1; });
  const doc = f.doc;
  /* text round trip */
  const again = DSL.parse(DSL.print(doc)).doc;
  if (JSON.stringify(again) !== JSON.stringify(doc)) { console.error(`✗ ${where}: print then parse changes the document`); errors += 1; }
  if (pubIds.has(f.id)) {
    const refs = [].concat(doc.given, doc.sequence, doc.from ? [doc.from] : []);
    refs.filter((r) => !pubIds.has(r)).forEach((r) => { console.error(`✗ ${where}: a public scenario refers to a private one (${r})`); errors += 1; });
  }
  const r = DSL.compile(f.id, all.docs);
  r.errors.forEach((e) => { console.error(`✗ ${where}: ${e.scenario}: ${e.message}`); errors += 1; });
  r.warnings.forEach((w) => { console.log(`! ${where}: ${w.scenario}: ${w.message}`); warnings += 1; });
  if (!r.json) continue;
  /* JSON round trip: compiled -> DSL (flat) -> compiled */
  const flat = DSL.fromJson(r.json);
  flat.id = '__check__';
  const lib2 = new Map(all.docs); lib2.set('__check__', DSL.parse(DSL.print(flat)).doc);
  const back = DSL.compile('__check__', lib2);
  if (JSON.stringify(DSL.canonical(back.json, true)) !== JSON.stringify(DSL.canonical(r.json, true))) { console.error(`✗ ${where}: JSON -> DSL -> JSON changes the scenario`); errors += 1; }
  const measured = r.json.phases.filter((p) => !p.setup).reduce((n, p) => n + p.steps.length, 0);
  const setup = r.json.phases.filter((p) => p.setup).reduce((n, p) => n + p.steps.length, 0);
  fs.writeFileSync(path.join(pubIds.has(f.id) ? outDirs.pub : outDirs.priv, `${f.id}.scenario.json`), JSON.stringify(r.json, null, 2) + '\n');
  console.log(`✓ ${f.id.padEnd(40)} ${String(measured).padStart(2)} measured, ${String(setup).padStart(2)} preconditions  ${doc.kind || ''}`);
}

const bundle = (name, list) => `/* Generated by scripts/scenarios-build.mjs from the .scn files: do not edit. */\nwindow.SCENARIO_LIBRARY = (window.SCENARIO_LIBRARY || []).concat(${JSON.stringify(list, null, 1)});\n`;
fs.writeFileSync(path.join(ROOT, 'scenarios/library.js'), bundle('library', pub));
fs.writeFileSync(path.join(ROOT, 'scenarios/library-private.js'), bundle('private', priv));
console.log(`${all.files.length} scenarios (${pub.length} public, ${priv.length} private), ${errors} error(s), ${warnings} warning(s).`);
if (errors) process.exit(1);
